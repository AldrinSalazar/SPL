// Regenerates the blog-sample entries in web/src/examples.ts from results/.
// Usage: node scripts/update-playground-samples.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const EXAMPLES_PATH = join(ROOT, "web", "src", "examples.ts");

// id, library chip label, and source file under results/.
const SAMPLES = [
  { id: "deepseek-v4-unknown", label: "DeepSeek V4", file: "Deepseek-v4 (Deepseek)/Deepseek-v4 unknown effort.spl" },
  { id: "gpt-5-6-sol-high", label: "GPT-5.6 Sol (high)", file: "GPT-5.6-Sol (Chat GPT)/GPT-5.6-Sol High.spl" },
  { id: "gpt-5-6-sol-medium", label: "GPT-5.6 Sol (medium)", file: "GPT-5.6-Sol (Chat GPT)/GPT-5.6-Sol Medium.spl" },
  { id: "gpt-5-6-sol-instant", label: "GPT-5.6 Sol (instant)", file: "GPT-5.6-Sol (Chat GPT)/GPT-5.6-Sol Instant.spl" },
  { id: "sonnet-5-max", label: "Sonnet 5 (max)", file: "Sonnet-5 (Claude)/Sonnet-5 Max.spl" },
  { id: "sonnet-5-medium", label: "Sonnet 5 (medium)", file: "Sonnet-5 (Claude)/Sonnet-5 Medium.spl" },
  { id: "gpt-6-astra-high", label: "GPT-6 Astra (high)", file: "GPT-6-Astra (Codex)/GPT-6-Astra high.spl" },
  { id: "muse-spark-1-3-max", label: "Muse Spark 1.3 (max)", file: "Muse-spark-1.3 (OpenRouter)/Muse-spark-1.3 Max.spl" },
  { id: "gemini-3-8-flash-high", label: "Gemini 3.8 Flash (high)", file: "Gemini-3.8-flash (OpenRouter)/Gemini-3.8-flash high.spl" },
  { id: "kimi-k3-max", label: "Kimi K3 (max)", file: "Kimi-k3 (OpenRouter)/Kimi-k3 max.spl" },
  { id: "grok-4-6-expert", label: "Grok 4.6 (expert)", file: "Grok 4.6 (X.com)/Grok-4.6 Expert.spl" },
];

const BEGIN = "  // BEGIN BLOG SAMPLES (generated by scripts/update-playground-samples.mjs - do not edit)";
const END = "  // END BLOG SAMPLES";

function escapeTemplate(source) {
  return source.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

const entries = SAMPLES.map(({ id, label, file }) => {
  const raw = readFileSync(join(ROOT, "results", file), "utf8");
  return (
    `  {\n    id: '${id}',\n    label: '${label}',\n    source: \`` +
    `${escapeTemplate(`${raw.trimEnd()}\n`)}\`` +
    `\n  }`
  );
});

const text = readFileSync(EXAMPLES_PATH, "utf8");
const start = text.indexOf(BEGIN);
const end = text.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  throw new Error("markers not found in web/src/examples.ts");
}
const next = `${text.slice(0, start + BEGIN.length)}\n${entries.join(",\n")},\n${text.slice(end)}`;
writeFileSync(EXAMPLES_PATH, next);
console.log(`wrote ${entries.length} samples to web/src/examples.ts`);
